// ===========================================================================
// WORD SEARCH WORKSHEET
// ===========================================================================
function generateWordsearchWorksheet(doc: any, terms: TermItem[], y: number): number {
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('Word Search', 50, y);
  y += 20;
  doc.setFontSize(10);
  doc.setFont('helvetica', 'italic');
  doc.setTextColor(0x66, 0x66, 0x66);
  doc.text('Find these words hidden in the grid (horizontally or vertically):', 50, y);
  doc.setTextColor(0, 0, 0);
  y += 25;

  const gridSize = 12;
  const grid: string[][] = Array.from({ length: gridSize }, () => Array(gridSize).fill(''));
  const words = terms.map(t => t.term.toUpperCase().replace(/[^A-Z]/g, '').slice(0, 10)).filter(w => w.length > 0).slice(0, 8);

  words.forEach((word, i) => {
    const row = i + 1;
    const col = 1;
    for (let c = 0; c < word.length && col + c < gridSize; c++) {
      grid[row][col + c] = word[c];
    }
  });

  for (let r = 0; r < gridSize; r++) {
    for (let c = 0; c < gridSize; c++) {
      if (!grid[r][c]) grid[r][c] = String.fromCharCode(65 + Math.floor(Math.random() * 26));
    }
  }

  const cellSize = 24;
  const gridStartX = 80;
  const gridStartY = y;
  doc.setFont('courier', 'bold');
  doc.setFontSize(14);
  for (let r = 0; r < gridSize; r++) {
    for (let c = 0; c < gridSize; c++) {
      const x = gridStartX + c * cellSize;
      const cy = gridStartY + r * cellSize;
      doc.setDrawColor(0xcc, 0xcc, 0xcc);
      doc.setLineWidth(0.5);
      doc.rect(x, cy, cellSize, cellSize);
      doc.text(grid[r][c], x + cellSize / 2, cy + 16, { align: 'center' });
    }
  }

  y = gridStartY + gridSize * cellSize + 30;
  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.text('Words to Find:', 50, y);
  y += 18;
  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  words.forEach((word, i) => {
    doc.text(`${i + 1}. ${word}`, 50, y);
    y += 14;
  });
  return y;
}

// ===========================================================================
// FLASH CARDS WORKSHEET
// ===========================================================================
function generateFlashCardsWorksheet(doc: any, terms: TermItem[], y: number): number {
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('Flash Cards', 50, y);
  y += 20;
  doc.setFontSize(10);
  doc.setFont('helvetica', 'italic');
  doc.setTextColor(0x66, 0x66, 0x66);
  doc.text('Cut along the lines to make individual flash cards.', 50, y);
  doc.setTextColor(0, 0, 0);
  y += 25;

  const cardW = 240;
  const cardH = 90;
  const pageW = doc.internal.pageSize.getWidth() - 100;
  const cols = Math.floor(pageW / cardW);
  const margin = (pageW - cols * cardW) / 2;
  let cardIdx = 0;

  terms.forEach((term) => {
    if (cardIdx >= cols * 3) { doc.addPage(); cardIdx = 0; y = 80; }
    const col = cardIdx % cols;
    const row = Math.floor(cardIdx / cols);
    const x = 50 + margin + col * cardW;
    const cy = 80 + row * (cardH + 10);

    doc.setDrawColor(0x7c, 0x3a, 0xed);
    doc.setLineWidth(1.5);
    doc.rect(x, cy, cardW, cardH);

    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    doc.text(term.emoji ?? '?', x + 10, cy + 20);
    doc.setFontSize(14);
    doc.setFont('helvetica', 'bold');
    doc.text(term.term, x + 10, cy + 40);

    doc.setDrawColor(0xcc, 0xcc, 0xcc);
    doc.setLineWidth(0.5);
    doc.setLineDashPattern([3, 3], 0);
    doc.line(x, cy + cardH / 2, x + cardW, cy + cardH / 2);
    doc.setLineDashPattern([], 0);

    doc.setFontSize(9);
    doc.setFont('helvetica', 'italic');
    doc.setTextColor(0x66, 0x66, 0x66);
    const def = doc.splitTextToSize(term.definition ?? '', cardW - 20);
    doc.text(def, x + 10, cy + cardH / 2 + 14);
    doc.setTextColor(0, 0, 0);

    cardIdx++;
  });
  return y;
}

// ===========================================================================
// MATCH UP WORKSHEET
// ===========================================================================
function generateMatchUpWorksheet(doc: any, terms: TermItem[], y: number): number {
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('Match Up', 50, y);
  y += 20;
  doc.setFontSize(10);
  doc.setFont('helvetica', 'italic');
  doc.setTextColor(0x66, 0x66, 0x66);
  doc.text('Draw a line to match each word with its definition.', 50, y);
  doc.setTextColor(0, 0, 0);
  y += 30;

  const shuffledDefs = [...terms].sort(() => Math.random() - 0.5);
  const leftX = 60;
  const rightX = 320;

  doc.setFontSize(11);
  terms.forEach((term, i) => {
    if (y > doc.internal.pageSize.getHeight() - 60) { doc.addPage(); y = 60; }
    doc.setFont('helvetica', 'bold');
    doc.text(`${i + 1}.`, leftX, y);
    doc.setFont('helvetica', 'normal');
    doc.text(term.term, leftX + 25, y);
    const letter = String.fromCharCode(65 + i);
    doc.setFont('helvetica', 'bold');
    doc.text(`${letter}.`, rightX, y);
    doc.setFont('helvetica', 'normal');
    const def = doc.splitTextToSize(shuffledDefs[i].definition ?? shuffledDefs[i].term, 200);
    doc.text(def, rightX + 25, y);
    y += 35;
  });

  y += 15;
  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.text('Answer Key:', 50, y);
  y += 18;
  terms.forEach((term, i) => {
    const matchLetter = String.fromCharCode(65 + shuffledDefs.findIndex(t => t.id === term.id));
    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    doc.text(`${i + 1}. -> ${matchLetter}`, 50, y);
    y += 14;
  });
  return y;
}

// ===========================================================================
// ANAGRAM WORKSHEET
// ===========================================================================
function generateAnagramWorksheet(doc: any, terms: TermItem[], y: number): number {
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('Anagram Puzzle', 50, y);
  y += 20;
  doc.setFontSize(10);
  doc.setFont('helvetica', 'italic');
  doc.setTextColor(0x66, 0x66, 0x66);
  doc.text('Unscramble the letters to spell each word.', 50, y);
  doc.setTextColor(0, 0, 0);
  y += 30;

  terms.forEach((term, i) => {
    if (y > doc.internal.pageSize.getHeight() - 80) { doc.addPage(); y = 60; }
    const word = term.term.toUpperCase();
    const scrambled = word.split('').sort(() => Math.random() - 0.5).join(' ');
    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    doc.text(`${i + 1}. Scrambled:`, 50, y);
    y += 18;
    doc.setFontSize(16);
    doc.setFont('courier', 'bold');
    doc.setTextColor(0x7c, 0x3a, 0xed);
    doc.text(`    ${scrambled}`, 50, y);
    doc.setTextColor(0, 0, 0);
    y += 16;
    doc.setFontSize(11);
    doc.setFont('helvetica', 'italic');
    doc.setTextColor(0x66, 0x66, 0x66);
    doc.text(`    Hint: ${term.definition ?? 'A vocabulary word'}`, 50, y);
    doc.setTextColor(0, 0, 0);
    y += 16;
    doc.setFontSize(12);
    doc.setFont('helvetica', 'normal');
    doc.text(`    Answer: ${'_'.repeat(word.length + 5)}`, 50, y);
    y += 30;
  });

  doc.addPage();
  y = 60;
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('Answer Key', 50, y);
  y += 25;
  terms.forEach((term, i) => {
    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    doc.text(`${i + 1}. ${term.term}`, 50, y);
    y += 14;
  });
  return y;
}
