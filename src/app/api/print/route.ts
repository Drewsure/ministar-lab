import { NextRequest, NextResponse } from 'next/server';
import type { TermItem } from '@/lib/types';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

// GET /api/print?mode=quiz&theme=space&terms=<base64-json>
// Generates a printable PDF worksheet for the given game mode + terms
export async function GET(req: NextRequest) {
  const url = req.nextUrl;
  const mode = url.searchParams.get('mode') ?? 'quiz';
  const termsB64 = url.searchParams.get('terms');

  if (!termsB64) {
    return NextResponse.json({ error: 'terms required' }, { status: 400 });
  }

  let terms: TermItem[];
  try {
    const cleanB64 = termsB64.replace(/-/g, '+').replace(/_/g, '/');
    const termsJson = Buffer.from(cleanB64, 'base64').toString('utf8');
    terms = JSON.parse(termsJson);
  } catch {
    return NextResponse.json({ error: 'invalid terms encoding' }, { status: 400 });
  }

  if (!Array.isArray(terms) || terms.length === 0) {
    return NextResponse.json({ error: 'no terms' }, { status: 400 });
  }

  // Dynamically import jspdf (pure JS, no external font files needed)
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ unit: 'pt', format: 'letter' });

  // Title header
  doc.setFontSize(24);
  doc.setFont('helvetica', 'bold');
  doc.text('MiniStar Lab', doc.internal.pageSize.getWidth() / 2, 50, { align: 'center' });
  doc.setFontSize(14);
  doc.setFont('helvetica', 'normal');
  doc.text(`${mode.charAt(0).toUpperCase() + mode.slice(1)} Worksheet`, doc.internal.pageSize.getWidth() / 2, 72, { align: 'center' });
  doc.setDrawColor(0x7c, 0x3a, 0xed);
  doc.setLineWidth(2);
  doc.line(50, 85, doc.internal.pageSize.getWidth() - 50, 85);

  // Name + Date
  doc.setFontSize(11);
  let y = 110;
  doc.text('Name: ____________________     Date: ___________', 50, y);
  y += 30;

  // Generate content based on mode
  switch (mode) {
    case 'quiz':
      y = generateQuizWorksheet(doc, terms, y);
      break;
    case 'crossword':
      y = generateCrosswordWorksheet(doc, terms, y);
      break;
    case 'wordsearch':
      y = generateWordsearchWorksheet(doc, terms, y);
      break;
    case 'flash-cards':
      y = generateFlashCardsWorksheet(doc, terms, y);
      break;
    case 'match-up':
      y = generateMatchUpWorksheet(doc, terms, y);
      break;
    case 'anagram':
      y = generateAnagramWorksheet(doc, terms, y);
      break;
    default:
      y = generateQuizWorksheet(doc, terms, y);
  }

  // Footer
  y = Math.max(y + 30, doc.internal.pageSize.getHeight() - 40);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'italic');
  doc.setTextColor(0x94, 0xa3, 0xb8);
  doc.text('Generated by MiniStar English Global Lab', doc.internal.pageSize.getWidth() / 2, doc.internal.pageSize.getHeight() - 25, { align: 'center' });

  const pdfBuffer = Buffer.from(doc.output('arraybuffer'));

  return new NextResponse(pdfBuffer, {
    headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `inline; filename="ministar-${mode}-worksheet.pdf"`,
      'Cache-Control': 'no-cache',
    },
  });
}

// ===========================================================================
// QUIZ WORKSHEET
// ===========================================================================
function generateQuizWorksheet(doc: any, terms: TermItem[], y: number): number {
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('Quiz Questions', 50, y);
  y += 25;

  terms.forEach((term, i) => {
    if (y > doc.internal.pageSize.getHeight() - 100) { doc.addPage(); y = 60; }
    const question = term.definition ?? `What is "${term.term}"?`;
    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    doc.text(`${i + 1}. ${question}`, 50, y);
    y += 18;

    const correct = term.term;
    const distractors = terms.filter(t => t.id !== term.id).slice(0, 3).map(t => t.term);
    const options = [...distractors, correct].sort(() => Math.random() - 0.5);
    const letters = ['A', 'B', 'C', 'D'];

    options.forEach((opt, j) => {
      const x = 70 + (j % 2) * 250;
      if (j % 2 === 0 && j > 0) y += 16;
      doc.setFontSize(11);
      doc.setFont('helvetica', 'normal');
      doc.text(`___ ${letters[j]}) ${opt}`, x, y);
    });
    y += 25;
  });

  // Answer key
  doc.addPage();
  y = 60;
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('Answer Key', 50, y);
  y += 25;
  terms.forEach((term, i) => {
    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    doc.text(`${i + 1}. ${term.term}`, 50, y);
    y += 16;
  });
  return y;
}

